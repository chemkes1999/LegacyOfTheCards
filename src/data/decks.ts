// Helper to repeat card IDs cleanly (up to 3 copies max per TCG rules)
function buildDeckList(entries: [string, number][]): string[] {
  const result: string[] = [];
  for (const [id, count] of entries) {
    for (let i = 0; i < count; i++) {
      result.push(id);
    }
  }
  return result;
}

